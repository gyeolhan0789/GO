/**
 * 계산한 값을 스타일용 퍼센트 문자열로 만든다.
 *
 * 스타일의 퍼센트 타입은 `${number}%`(템플릿 리터럴 타입)라서, 보간하는 값이
 * number여야 한다. `toFixed()`처럼 문자열을 거치면 `${string}%`가 되어 타입이
 * 어긋난다. 그래서 반올림도 숫자 단계에서 끝낸다.
 *
 * 두 가지를 같이 막는다.
 *
 * 1. **부동소수점 꼬리** — `(0.5 - 0.508) * 100`은 `-0.8000000000000007`이 된다.
 *    렌더에는 영향이 없지만 스타일 값으로 읽기 어렵다. 소수 3자리에서 자른다.
 *    3자리면 512px 캔버스에서 0.005px 미만이라 위치가 달라지지 않는다.
 * 2. **NaN·Infinity** — 0으로 나눈 값이 그대로 흘러오면 `"NaN%"`가 된다. 네이티브
 *    파싱이 실패해 레이아웃이 조용히 깨지므로, 안전한 `0%`로 떨어뜨린다.
 *
 * 나눠떨어지지 않는 비율을 일부러 그대로 써야 하는 곳(예: 열 7개를 `100 / 7`로
 * 나누는 격자)에는 쓰지 않는다. 반올림하면 합이 100%를 넘어 줄이 밀린다.
 */
export function percent(value: number): `${number}%` {
  if (!Number.isFinite(value)) {
    return '0%';
  }
  return `${Math.round(value * 1000) / 1000}%`;
}
